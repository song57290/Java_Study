package sec02.exam04;

public class CharExample {
	public static void main(String[] args) {
		
		char c1 = 'A';
		char c2 = 65; // 65에 대한 문자열을 반환 => A를 반환 
		char c3 = '가';
		char c4 = '각';
		
		System.out.println(c1);
		System.out.println(c2);
		System.out.println(c3);
		System.out.println(c4);
		
	}
}
